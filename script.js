// Data-driven gallery. Replace cover/preview with image URLs and link with the project URL.
(() => {
  const grid = document.getElementById('projects-grid');
  const counter = document.getElementById('project-count');
  counter.textContent = String(projects.length).padStart(2, '0') + ' ITEMS';
  document.getElementById('project-total').textContent = `${projects.length} 個作品`;
  const fine = matchMedia('(hover: hover) and (pointer: fine) and (min-width: 701px)');
  const preview = document.createElement('div');
  preview.className = 'gallery-preview';
  preview.setAttribute('aria-hidden', 'true');
  preview.setAttribute('popover', 'manual');
  const previewImage = new Image(); previewImage.alt = '';
  preview.append(previewImage); document.body.append(preview);
  let current = null, request = 0, hideTimer;
  function hidePreview() {
    current = null; request++; clearTimeout(hideTimer);
    preview.classList.remove('visible'); grid.classList.remove('previewing');
    grid.querySelectorAll('.is-previewed').forEach(card => card.classList.remove('is-previewed'));
    hideTimer = setTimeout(() => { if (!current && preview.matches(':popover-open')) preview.hidePopover(); }, 330);
  }
  function positionPreview(card) {
    const box = card.querySelector('.project-cover').getBoundingClientRect();
    const width = Math.max(1, Math.min(box.width * 1.5, innerWidth - 24, 560));
    const height = Math.max(1, Math.min(box.height * 1.5, innerHeight - 110, 650));
    const left = Math.max(12, Math.min(innerWidth - width - 12, box.left + (box.width - width) / 2));
    const top = Math.max(52, Math.min(innerHeight - height - 58, box.top + (box.height - height) / 2));
    Object.assign(preview.style, {width:`${width}px`,height:`${height}px`,left:`${left}px`,top:`${top}px`});
  }
  function showPreview(card, project) {
    if (!fine.matches) return;
    clearTimeout(hideTimer); current = card;
    const version = ++request;
    preview.classList.remove('visible');
    const image = new Image();
    image.onload = () => {
      if (version !== request || current !== card) return;
      previewImage.src = image.src; positionPreview(card);
      grid.querySelectorAll('.is-previewed').forEach(c => c.classList.remove('is-previewed'));
      card.classList.add('is-previewed'); grid.classList.add('previewing');
      if (typeof preview.showPopover === 'function' && !preview.matches(':popover-open')) preview.showPopover();
      requestAnimationFrame(() => { if (version === request) preview.classList.add('visible'); });
    };
    image.onerror = hidePreview;
    image.src = project.preview || project.cover;
  }
  function openProject(project) {
    hidePreview();
    const body = document.getElementById('detail-body');
    const image = new Image(); image.src = project.preview || project.cover;
    image.alt = project.title + '完整封面'; image.className = 'project-detail-cover';
    const title = document.createElement('h3'); title.textContent = project.title;
    const category = document.createElement('p'); category.className = 'type'; category.textContent = project.category;
    const text = document.createElement('p'); text.textContent = project.description || '';
    body.replaceChildren(image, title, category);
    if (project.sections?.length) {
      for (const section of project.sections) {
        const block = document.createElement('section'); block.className = 'project-story';
        const heading = document.createElement('h4'); heading.textContent = section.title; block.append(heading);
        for (const paragraph of section.paragraphs) {
          const p = document.createElement('p');
          paragraph.split(/(\*\*.*?\*\*)/g).forEach(part => {
            if (part.startsWith('**') && part.endsWith('**')) {
              const strong = document.createElement('strong'); strong.textContent = part.slice(2, -2); p.append(strong);
            } else p.append(document.createTextNode(part));
          });
          block.append(p);
        }
        body.append(block);
      }
    } else body.append(text);
    if (project.images?.length) {
      const gallery = document.createElement('div'); gallery.className = 'project-image-sequence';
      for (const item of project.images) {
        const figure = document.createElement('figure');
        const img = new Image(); img.src = item.src; img.alt = item.alt;
        img.loading = 'lazy'; img.decoding = 'async';
        const link = document.createElement('a'); link.href = item.src; link.target = '_blank'; link.rel = 'noopener';
        link.setAttribute('aria-label', item.alt + '，開啟完整圖片'); link.append(img); figure.append(link); gallery.append(figure);
      }
      body.append(gallery);
    }
    if (project.demo) {
      const note = document.createElement('p'); note.className = 'pending';
      note.textContent = '此為版型示範，非謝沛璇本人實際作品。'; body.append(note);
    }
    document.getElementById('detail-title').textContent = project.title;
    openWindow('detail'); body.scrollTop = 0;
  }
  projects.forEach(project => {
    const card = document.createElement('a'); card.className = 'project gallery-card';
    card.href = project.link; card.setAttribute('aria-label', `${project.title} — ${project.category}，查看作品`);
    const image = new Image(); image.className = 'project-cover'; image.src = project.cover;
    image.alt = project.title + '作品封面'; image.width = 720; image.height = 600; image.decoding = 'async';
    const caption = document.createElement('span'); caption.className = 'project-caption';
    const title = document.createElement('strong'); title.textContent = project.title;
    const category = document.createElement('span'); category.textContent = project.category + ' ↗';
    caption.append(title, category); card.append(image, caption); grid.append(card);
    card.addEventListener('pointerenter', e => { if (e.pointerType === 'mouse') showPreview(card, project); });
    card.addEventListener('pointerleave', hidePreview);
    card.addEventListener('focus', () => showPreview(card, project));
    card.addEventListener('blur', hidePreview);
    card.addEventListener('click', event => {
      hidePreview();
      if (project.link.startsWith('#project/') && !event.ctrlKey && !event.metaKey && !event.shiftKey && !event.altKey) {
        event.preventDefault(); history.pushState(null, '', project.link); openProject(project);
      }
    });
  });
  function route() {
    const project = projects.find(p => p.link === location.hash);
    if (project) openProject(project);
    else if (!document.getElementById('detail').hidden) hideWindow(document.getElementById('detail'), true);
  }
  addEventListener('popstate', route); addEventListener('hashchange', route);
  addEventListener('resize', hidePreview); addEventListener('scroll', hidePreview, true);
  addEventListener('blur', hidePreview); fine.addEventListener('change', hidePreview);
  document.addEventListener('pointerdown', hidePreview, true);
  document.addEventListener('keydown', e => { if (e.key === 'Escape') hidePreview(); });
  if (location.hash.startsWith('#project/')) route();
})();
